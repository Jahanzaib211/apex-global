import "server-only";
import { enrichLead, resolveProvider } from "@apex/ai";
import { prisma } from "@apex/db";

/**
 * Background lead enrichment.
 *
 * Deliberately fire-and-forget: the lead is committed before this runs, so a
 * provider outage costs a summary, never an enquiry. Every failure path is
 * swallowed and logged.
 *
 * This is the interim home for the work. It belongs on the BullMQ worker tier
 * (retries, backoff, a dead-letter queue); an un-awaited promise in a request
 * handler can be cut short if the process is recycled mid-flight, which for
 * an advisory summary is an acceptable trade and for a notification would not
 * be.
 */
export async function enrichLeadInBackground(leadId: string): Promise<void> {
  try {
    const integrations = await prisma.integration.findMany({
      where: { isEnabled: true },
      select: {
        provider: true,
        isEnabled: true,
        secretCiphertext: true,
        secretIv: true,
        secretTag: true,
        config: true,
      },
    });

    const provider = resolveProvider(integrations);
    if (!provider) return; // No AI configured — a normal state, not an error.

    const lead = await prisma.lead.findUnique({ where: { id: leadId } });
    if (!lead) return;

    const result = await enrichLead(
      {
        name: lead.name,
        company: lead.companyName,
        country: lead.country,
        interest: lead.interestSlug,
        budget: lead.budgetBand,
        timeline: lead.timeline,
        companySize: lead.companySize,
        message: lead.message ?? lead.requirements,
      },
      provider,
    );

    if (!result.summary && result.score === null) return;

    await prisma.$transaction([
      prisma.lead.update({
        where: { id: leadId },
        data: {
          aiSummary: result.summary,
          aiScore: result.score,
          aiScoredAt: new Date(),
          aiModel: result.model,
        },
      }),
      prisma.leadActivity.create({
        data: {
          leadId,
          type: "ai_summary",
          // Recorded as advisory on the timeline so nobody mistakes a model's
          // opinion for a colleague's.
          summary: `AI summary generated by ${result.model ?? provider.id}`,
          detail: result.summary,
          meta: { score: result.score, provider: provider.id, advisory: true },
        },
      }),
    ]);
  } catch (error) {
    console.warn("Lead enrichment failed (lead is unaffected):", error);
  }
}
